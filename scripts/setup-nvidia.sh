#!/usr/bin/env bash
# ==============================================================================
# yusei-hypr: NVIDIA Kernel & Bootloader Provisioning Module
# ==============================================================================

set -euo pipefail

GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m'

DRY_RUN=false
for arg in "$@"; do
    case "$arg" in
        --dry-run)
            DRY_RUN=true
            ;;
        -y|--yes)
            ;;
        -h|--help)
            echo "Usage: $(basename "$0") [--dry-run] [-y|--yes] [-h|--help]"
            exit 0
            ;;
        *)
            ;;
    esac
done

MKINITCPIO_CONF="${MKINITCPIO_CONF:-/etc/mkinitcpio.conf}"
GRUB_DEFAULT_FILE="${GRUB_DEFAULT_FILE:-/etc/default/grub}"
LOADER_ENTRY_DIRS="${LOADER_ENTRY_DIRS:-/boot/loader/entries:/efi/loader/entries:/boot/efi/loader/entries}"
MODPROBE_NVIDIA_CONF="${MODPROBE_NVIDIA_CONF:-/etc/modprobe.d/nvidia.conf}"
DETECTED_ENV_FILE="${DETECTED_ENV_FILE:-/tmp/yusei-hypr/detected.env}"

STATE_HOME="${XDG_STATE_HOME:-$HOME/.local/state}"
STATE_DIR="$STATE_HOME/yusei-hypr"
NVIDIA_STATE_FILE="$STATE_DIR/nvidia-state.env"

echo -e "${BLUE}:: [NVIDIA Setup] Thiết lập cấu hình chuyên sâu cho card NVIDIA...${NC}"

# Nạp thông tin phần cứng (cho phép test override qua env HAS_NVIDIA)
HAS_NVIDIA="${HAS_NVIDIA:-}"
if [ -z "$HAS_NVIDIA" ]; then
    HAS_NVIDIA="false"
    if [ -f "$DETECTED_ENV_FILE" ]; then
        # shellcheck disable=SC1090
        . "$DETECTED_ENV_FILE"
    fi
fi

if [ "$HAS_NVIDIA" != "true" ]; then
    echo -e "${GREEN}✓ Hệ thống không dùng GPU NVIDIA (Intel / AMD Radeon). Bỏ qua bước này.${NC}"
    exit 0
fi

needs_sudo_for_path() {
    local p="$1"
    if [ "${EUID:-$(id -u)}" -eq 0 ]; then
        return 1
    fi
    if [ -e "$p" ]; then
        [ ! -w "$p" ]
        return $?
    fi
    local parent
    parent="$(dirname "$p")"
    while [ "$parent" != "/" ] && [ ! -e "$parent" ]; do
        parent="$(dirname "$parent")"
    done
    [ ! -w "$parent" ]
}

run_for_path() {
    local p="$1"
    shift
    if needs_sudo_for_path "$p"; then
        sudo "$@"
    else
        "$@"
    fi
}

write_file_content() {
    local target="$1"
    local src="$2"
    local parent
    parent="$(dirname "$target")"
    if [ ! -d "$parent" ]; then
        run_for_path "$parent" mkdir -p "$parent"
    fi
    if needs_sudo_for_path "$target"; then
        sudo tee "$target" >/dev/null < "$src"
    else
        cat "$src" > "$target"
    fi
}

# Đọc trạng thái cũ nếu đã tồn tại để giữ tính idempotent khi chạy lại
PREV_ADDED_MKINITCPIO_MODULES=""
PREV_GRUB_MODESET_ADDED="false"
PREV_LOADER_ENTRIES_MODIFIED=""
PREV_MODPROBE_CREATED="false"
if [ -f "$NVIDIA_STATE_FILE" ]; then
    prev_tmp="$(mktemp)"
    # shellcheck disable=SC1090
    (
        ADDED_MKINITCPIO_MODULES=""
        GRUB_MODESET_ADDED="false"
        LOADER_ENTRIES_MODIFIED=""
        MODPROBE_CREATED="false"
        . "$NVIDIA_STATE_FILE"
        printf '%s\n%s\n%s\n%s\n' \
            "${ADDED_MKINITCPIO_MODULES:-}" \
            "${GRUB_MODESET_ADDED:-false}" \
            "${LOADER_ENTRIES_MODIFIED:-}" \
            "${MODPROBE_CREATED:-false}"
    ) > "$prev_tmp" 2>/dev/null || true
    if [ -s "$prev_tmp" ]; then
        mapfile -t _prev_lines < "$prev_tmp"
        PREV_ADDED_MKINITCPIO_MODULES="${_prev_lines[0]:-}"
        PREV_GRUB_MODESET_ADDED="${_prev_lines[1]:-false}"
        PREV_LOADER_ENTRIES_MODIFIED="${_prev_lines[2]:-}"
        PREV_MODPROBE_CREATED="${_prev_lines[3]:-false}"
    fi
    rm -f "$prev_tmp"
fi

ADDED_MODULES_NOW=""
GRUB_MODESET_ADDED_NOW="false"
LOADER_ENTRIES_NOW=()
MODPROBE_CREATED_NOW="false"

echo -e "${YELLOW}:: Đang tiến hành cấu hình Kernel, Initramfs và Bootloader cho NVIDIA...${NC}"

# 1. Cấu hình Modprobe (/etc/modprobe.d/nvidia.conf)
echo -e "${BLUE}:: [1/3] Cấu hình tham số kernel module (${MODPROBE_NVIDIA_CONF})...${NC}"
if [ -n "$MODPROBE_NVIDIA_CONF" ]; then
    if [ ! -e "$MODPROBE_NVIDIA_CONF" ]; then
        if [ "$DRY_RUN" = "true" ]; then
            echo -e "${YELLOW}[DRY-RUN] Sẽ tạo ${MODPROBE_NVIDIA_CONF} với: options nvidia_drm modeset=1 fbdev=1${NC}"
        else
            tmp_modprobe="$(mktemp)"
            cat << 'EOF' > "$tmp_modprobe"
# Generated by yusei-hypr installer (JaKooLit parity)
options nvidia_drm modeset=1 fbdev=1
EOF
            write_file_content "$MODPROBE_NVIDIA_CONF" "$tmp_modprobe"
            rm -f "$tmp_modprobe"
            MODPROBE_CREATED_NOW="true"
            echo -e "${GREEN}✓ Đã tạo ${MODPROBE_NVIDIA_CONF} với options: modeset=1 fbdev=1${NC}"
        fi
    else
        if grep -Eq '^[[:space:]]*options[[:space:]]+nvidia_drm\b.*\bmodeset=1\b' "$MODPROBE_NVIDIA_CONF" && \
           grep -Eq '^[[:space:]]*options[[:space:]]+nvidia_drm\b.*\bfbdev=1\b' "$MODPROBE_NVIDIA_CONF"; then
            echo -e "${GREEN}✓ ${MODPROBE_NVIDIA_CONF} đã có sẵn cấu hình modeset=1 fbdev=1.${NC}"
        else
            if [ "$DRY_RUN" = "true" ]; then
                echo -e "${YELLOW}[DRY-RUN] Sẽ sao lưu và cập nhật ${MODPROBE_NVIDIA_CONF} với: options nvidia_drm modeset=1 fbdev=1${NC}"
            else
                run_for_path "$MODPROBE_NVIDIA_CONF" cp -a "$MODPROBE_NVIDIA_CONF" "${MODPROBE_NVIDIA_CONF}.bak_$(date +%Y%m%d_%H%M%S)"
                tmp_modprobe="$(mktemp)"
                cat << 'EOF' > "$tmp_modprobe"
# Generated by yusei-hypr installer (JaKooLit parity)
options nvidia_drm modeset=1 fbdev=1
EOF
                write_file_content "$MODPROBE_NVIDIA_CONF" "$tmp_modprobe"
                rm -f "$tmp_modprobe"
                echo -e "${GREEN}✓ Đã cập nhật ${MODPROBE_NVIDIA_CONF} với options: modeset=1 fbdev=1${NC}"
            fi
        fi
    fi
fi

# 2. Cấu hình Initramfs (/etc/mkinitcpio.conf)
echo -e "${BLUE}:: [2/3] Kiểm tra nạp module sớm (Early KMS) trong ${MKINITCPIO_CONF}...${NC}"
if [ -f "$MKINITCPIO_CONF" ]; then
    tmp_mkinit_out="$(mktemp)"
    added_modules_out="$(python3 - "$MKINITCPIO_CONF" "$tmp_mkinit_out" << 'PYEOF'
import re
import sys

src_path, out_path = sys.argv[1], sys.argv[2]
target_modules = ["nvidia", "nvidia_modeset", "nvidia_uvm", "nvidia_drm"]

with open(src_path, "r", encoding="utf-8") as f:
    text = f.read()

lines = text.splitlines(keepends=True)

def split_code_comment(s, in_sq=False, in_dq=False):
    i = 0
    while i < len(s):
        c = s[i]
        if c == "\\" and not in_sq and i + 1 < len(s):
            i += 2
            continue
        if c == "'" and not in_dq:
            in_sq = not in_sq
        elif c == '"' and not in_sq:
            in_dq = not in_dq
        elif c == "#" and not in_sq and not in_dq:
            return s[:i], s[i:], in_sq, in_dq
        i += 1
    return s, "", in_sq, in_dq

def tokenize_items(s):
    tokens = []
    for raw in s.split():
        tok = raw.strip().strip('"').strip("'")
        if tok:
            tokens.append(tok)
    return tokens

# Locate active MODULES=(...) or legacy MODULES="..." / '...'
found_mode = None
start_idx = -1
end_idx = -1
close_pos = -1

for idx, line in enumerate(lines):
    m_arr = re.match(r'^([ \t]*MODULES=\()(.*)$', line, re.DOTALL)
    if m_arr:
        found_mode = "array"
        start_idx = idx
        # Scan from after '(' to find matching ')' outside comments and quotes
        in_sq = False
        in_dq = False
        j = idx
        pos = len(m_arr.group(1))
        while j < len(lines):
            cur = lines[j]
            k = pos
            while k < len(cur):
                ch = cur[k]
                if ch == "\\" and not in_sq and k + 1 < len(cur):
                    k += 2
                    continue
                if ch == "'" and not in_dq:
                    in_sq = not in_sq
                elif ch == '"' and not in_sq:
                    in_dq = not in_dq
                elif ch == "#" and not in_sq and not in_dq:
                    break
                elif ch == ")" and not in_sq and not in_dq:
                    end_idx = j
                    close_pos = k
                    break
                k += 1
            if end_idx != -1:
                break
            j += 1
            pos = 0
        if end_idx != -1:
            break
        found_mode = None
        start_idx = -1

if found_mode is None:
    for idx, line in enumerate(lines):
        m_str = re.match(r'^([ \t]*MODULES=)(["\'])(.*)$', line, re.DOTALL)
        if m_str:
            q = m_str.group(2)
            rest = m_str.group(3)
            # Find closing quote
            k = 0
            closed = -1
            while k < len(rest):
                if rest[k] == "\\" and q == '"' and k + 1 < len(rest):
                    k += 2
                    continue
                if rest[k] == q:
                    closed = k
                    break
                k += 1
            if closed != -1:
                found_mode = "string"
                start_idx = idx
                end_idx = idx
                close_pos = len(m_str.group(1)) + 1 + closed
                break

if found_mode is None:
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)
    print("")
    sys.exit(0)

existing = set()
if found_mode == "array":
    in_sq = False
    in_dq = False
    for j in range(start_idx, end_idx + 1):
        cur = lines[j]
        seg_start = len(re.match(r'^[ \t]*MODULES=\(', cur).group(0)) if j == start_idx else 0
        seg_end = close_pos if j == end_idx else len(cur)
        seg = cur[seg_start:seg_end]
        code, _, in_sq, in_dq = split_code_comment(seg, in_sq, in_dq)
        existing.update(tokenize_items(code))

    missing = [m for m in target_modules if m not in existing]
    if not missing:
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(text)
        print("")
        sys.exit(0)

    add_str = " ".join(missing)
    if start_idx == end_idx:
        line = lines[start_idx]
        prefix = re.match(r'^[ \t]*MODULES=\(', line).group(0)
        inner = line[len(prefix):close_pos]
        suffix = line[close_pos:]
        inner_stripped = inner.strip()
        if inner_stripped:
            new_inner = inner.rstrip() + " " + add_str
        else:
            new_inner = add_str
        lines[start_idx] = prefix + new_inner + suffix
    else:
        close_line = lines[end_idx]
        before_close = close_line[:close_pos]
        after_close = close_line[close_pos:]
        if before_close.strip():
            lines[end_idx] = before_close.rstrip() + " " + add_str + after_close
        else:
            indent = "    "
            for j in range(start_idx + 1, end_idx):
                stripped = lines[j].lstrip(" \t")
                if stripped and not stripped.startswith("#") and stripped != "\n":
                    indent = lines[j][:len(lines[j]) - len(stripped)]
                    break
            nl = "\r\n" if close_line.endswith("\r\n") else "\n"
            lines.insert(end_idx, f"{indent}{add_str}{nl}")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("".join(lines))
    print(add_str)
else:
    line = lines[start_idx]
    m_str = re.match(r'^([ \t]*MODULES=)(["\'])', line)
    prefix = m_str.group(1)
    q = m_str.group(2)
    inner = line[len(prefix) + 1:close_pos]
    suffix = line[close_pos:]
    existing.update(tokenize_items(inner))
    missing = [m for m in target_modules if m not in existing]
    if not missing:
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(text)
        print("")
        sys.exit(0)
    add_str = " ".join(missing)
    if inner.strip():
        new_inner = inner.rstrip() + " " + add_str
    else:
        new_inner = add_str
    lines[start_idx] = prefix + q + new_inner + suffix
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("".join(lines))
    print(add_str)
PYEOF
)"

    if [ -n "$added_modules_out" ]; then
        echo -e "${YELLOW}Module còn thiếu trong MODULES: ${added_modules_out}${NC}"
        if [ "$DRY_RUN" = "true" ]; then
            echo -e "${YELLOW}[DRY-RUN] Sẽ sao lưu và cập nhật MODULES trong ${MKINITCPIO_CONF} (thêm: ${added_modules_out})${NC}"
            if [ "$MKINITCPIO_CONF" = "/etc/mkinitcpio.conf" ]; then
                echo -e "${YELLOW}[DRY-RUN] Sẽ chạy: sudo mkinitcpio -P${NC}"
            fi
        else
            echo -e "${BLUE}:: Sao lưu ${MKINITCPIO_CONF} trước khi cập nhật...${NC}"
            run_for_path "$MKINITCPIO_CONF" cp -a "$MKINITCPIO_CONF" "${MKINITCPIO_CONF}.bak_$(date +%Y%m%d_%H%M%S)"
            write_file_content "$MKINITCPIO_CONF" "$tmp_mkinit_out"
            ADDED_MODULES_NOW="$added_modules_out"
            echo -e "${GREEN}✓ Đã cập nhật MODULES trong ${MKINITCPIO_CONF}${NC}"
            if [ "$MKINITCPIO_CONF" = "/etc/mkinitcpio.conf" ] && command -v mkinitcpio &>/dev/null; then
                echo -e "${BLUE}:: Đang biên dịch lại initramfs qua 'mkinitcpio -P'...${NC}"
                sudo mkinitcpio -P
                echo -e "${GREEN}✓ Đã tạo lại initramfs thành công!${NC}"
            fi
        fi
    else
        echo -e "${GREEN}✓ Toàn bộ module NVIDIA đã có mặt trong ${MKINITCPIO_CONF}.${NC}"
    fi
    rm -f "$tmp_mkinit_out"
else
    echo -e "${YELLOW}⚠️ Không tìm thấy ${MKINITCPIO_CONF} (có thể hệ thống dùng booster hoặc dracut).${NC}"
fi

# 3. Cấu hình Bootloader Kernel Parameter (GRUB / systemd-boot)
echo -e "${BLUE}:: [3/3] Kiểm tra tham số dòng lệnh Bootloader...${NC}"
BOOTLOADER_FOUND=false

if [ -f "$GRUB_DEFAULT_FILE" ]; then
    BOOTLOADER_FOUND=true
    tmp_grub_out="$(mktemp)"
    grub_changed="$(python3 - "$GRUB_DEFAULT_FILE" "$tmp_grub_out" << 'PYEOF'
import re
import sys

src_path, out_path = sys.argv[1], sys.argv[2]
with open(src_path, "r", encoding="utf-8") as f:
    lines = f.read().splitlines(keepends=True)

changed = False
for idx, line in enumerate(lines):
    m = re.match(r'^([ \t]*GRUB_CMDLINE_LINUX_DEFAULT=)(["\'])(.*)$', line, re.DOTALL)
    if not m:
        continue
    prefix = m.group(1)
    q = m.group(2)
    rest = m.group(3)
    # Find matching closing quote (supporting \" escape in double quotes)
    k = 0
    close_idx = -1
    while k < len(rest):
        if rest[k] == "\\" and q == '"' and k + 1 < len(rest):
            k += 2
            continue
        if rest[k] == q:
            close_idx = k
            break
        k += 1
    if close_idx == -1:
        continue
    inner = rest[:close_idx]
    suffix = rest[close_idx:]  # starts with closing quote
    tokens = inner.split()
    if "nvidia_drm.modeset=1" in tokens or "nvidia-drm.modeset=1" in tokens:
        break
    if inner.strip():
        new_inner = inner.rstrip() + " nvidia_drm.modeset=1"
    else:
        new_inner = "nvidia_drm.modeset=1"
    lines[idx] = prefix + q + new_inner + suffix
    changed = True
    break

with open(out_path, "w", encoding="utf-8") as f:
    f.write("".join(lines))

print("true" if changed else "false")
PYEOF
)"

    if [ "$grub_changed" = "true" ]; then
        if [ "$DRY_RUN" = "true" ]; then
            echo -e "${YELLOW}[DRY-RUN] Sẽ sao lưu và thêm 'nvidia_drm.modeset=1' vào GRUB_CMDLINE_LINUX_DEFAULT trong ${GRUB_DEFAULT_FILE}${NC}"
            if [ "$GRUB_DEFAULT_FILE" = "/etc/default/grub" ]; then
                echo -e "${YELLOW}[DRY-RUN] Sẽ chạy: sudo grub-mkconfig -o /boot/grub/grub.cfg${NC}"
            fi
        else
            echo -e "${YELLOW}Thêm 'nvidia_drm.modeset=1' vào GRUB_CMDLINE_LINUX_DEFAULT trong ${GRUB_DEFAULT_FILE}...${NC}"
            run_for_path "$GRUB_DEFAULT_FILE" cp -a "$GRUB_DEFAULT_FILE" "${GRUB_DEFAULT_FILE}.bak_$(date +%Y%m%d_%H%M%S)"
            write_file_content "$GRUB_DEFAULT_FILE" "$tmp_grub_out"
            GRUB_MODESET_ADDED_NOW="true"
            if [ "$GRUB_DEFAULT_FILE" = "/etc/default/grub" ]; then
                if command -v grub-mkconfig &>/dev/null && [ -d /boot/grub ]; then
                    echo -e "${BLUE}:: Cập nhật cấu hình GRUB (grub-mkconfig)...${NC}"
                    sudo grub-mkconfig -o /boot/grub/grub.cfg
                    echo -e "${GREEN}✓ Đã cập nhật GRUB thành công!${NC}"
                else
                    echo -e "${YELLOW}⚠️ Đã cập nhật ${GRUB_DEFAULT_FILE}; hãy chạy 'sudo grub-mkconfig -o /boot/grub/grub.cfg' nếu dùng GRUB.${NC}"
                fi
            else
                echo -e "${GREEN}✓ Đã cập nhật ${GRUB_DEFAULT_FILE}!${NC}"
            fi
        fi
    else
        echo -e "${GREEN}✓ GRUB đã có sẵn tham số modeset cho NVIDIA.${NC}"
    fi
    rm -f "$tmp_grub_out"
fi

# Kiểm tra systemd-boot loader entries (/boot/loader/entries, /efi/loader/entries, /boot/efi/loader/entries)
IFS=': ' read -ra _loader_dirs <<< "$LOADER_ENTRY_DIRS"
SEEN_LOADER_DIRS=()
ENTRIES_UPDATED=0
ENTRIES_FOUND=0

for entry_dir in "${_loader_dirs[@]}"; do
    [ -n "$entry_dir" ] && [ -d "$entry_dir" ] || continue
    real_entry_dir="$(readlink -f "$entry_dir" 2>/dev/null || echo "$entry_dir")"
    dir_seen=false
    for seen in "${SEEN_LOADER_DIRS[@]:-}"; do
        if [ "$seen" = "$real_entry_dir" ]; then
            dir_seen=true
            break
        fi
    done
    [ "$dir_seen" = "true" ] && continue
    SEEN_LOADER_DIRS+=("$real_entry_dir")

    BOOTLOADER_FOUND=true
    echo -e "${BLUE}:: Phát hiện systemd-boot entries tại ${entry_dir}. Kiểm tra các file entry...${NC}"

    shopt -s nullglob
    for entry in "$entry_dir"/*.conf; do
        [ -f "$entry" ] || continue
        ENTRIES_FOUND=$((ENTRIES_FOUND + 1))
        tmp_entry_out="$(mktemp)"
        entry_changed="$(python3 - "$entry" "$tmp_entry_out" << 'PYEOF'
import re
import sys

src_path, out_path = sys.argv[1], sys.argv[2]
with open(src_path, "r", encoding="utf-8") as f:
    lines = f.read().splitlines(keepends=True)

def split_inline_comment(line_no_nl):
    in_sq = False
    in_dq = False
    i = 0
    while i < len(line_no_nl):
        c = line_no_nl[i]
        if c == "\\" and not in_sq and i + 1 < len(line_no_nl):
            i += 2
            continue
        if c == "'" and not in_dq:
            in_sq = not in_sq
        elif c == '"' and not in_sq:
            in_dq = not in_dq
        elif c == "#" and not in_sq and not in_dq:
            return line_no_nl[:i], line_no_nl[i:]
        i += 1
    return line_no_nl, ""

already_present = False
first_options_idx = -1

for idx, line in enumerate(lines):
    nl = "\r\n" if line.endswith("\r\n") else ("\n" if line.endswith("\n") else "")
    body = line[:-len(nl)] if nl else line
    if re.match(r'^[ \t]*#', body):
        continue
    if re.match(r'^[ \t]*options(?:[ \t]+|$)', body):
        if first_options_idx == -1:
            first_options_idx = idx
        code_part, _ = split_inline_comment(body)
        tokens = code_part.split()[1:]
        if "nvidia_drm.modeset=1" in tokens or "nvidia-drm.modeset=1" in tokens:
            already_present = True
            break

changed = False
if not already_present and first_options_idx != -1:
    line = lines[first_options_idx]
    nl = "\r\n" if line.endswith("\r\n") else ("\n" if line.endswith("\n") else "")
    body = line[:-len(nl)] if nl else line
    code_part, comment_part = split_inline_comment(body)
    code_stripped = code_part.rstrip(" \t")
    ws_before_comment = code_part[len(code_stripped):]
    if comment_part:
        if not ws_before_comment:
            ws_before_comment = " "
        new_body = f"{code_stripped} nvidia_drm.modeset=1{ws_before_comment}{comment_part}"
    else:
        new_body = f"{code_stripped} nvidia_drm.modeset=1"
    lines[first_options_idx] = new_body + nl
    changed = True

with open(out_path, "w", encoding="utf-8") as f:
    f.write("".join(lines))

print("true" if changed else "false")
PYEOF
)"

        if [ "$entry_changed" = "true" ]; then
            ENTRIES_UPDATED=$((ENTRIES_UPDATED + 1))
            if [ "$DRY_RUN" = "true" ]; then
                echo -e "${YELLOW}[DRY-RUN] Sẽ sao lưu và bổ sung 'nvidia_drm.modeset=1' vào options của ${entry}${NC}"
            else
                echo -e "${YELLOW}Bổ sung 'nvidia_drm.modeset=1' vào options của ${entry}...${NC}"
                run_for_path "$entry" cp -a "$entry" "${entry}.bak_$(date +%Y%m%d_%H%M%S)"
                write_file_content "$entry" "$tmp_entry_out"
                LOADER_ENTRIES_NOW+=("$entry")
            fi
        fi
        rm -f "$tmp_entry_out"
    done
    shopt -u nullglob
done

if [ "$ENTRIES_FOUND" -gt 0 ]; then
    if [ "$ENTRIES_UPDATED" -gt 0 ]; then
        if [ "$DRY_RUN" = "false" ]; then
            echo -e "${GREEN}✓ Đã cập nhật $ENTRIES_UPDATED mục khởi động trong systemd-boot!${NC}"
        fi
    else
        echo -e "${GREEN}✓ systemd-boot entries đã chứa tham số modeset cho NVIDIA.${NC}"
    fi
fi

if [ "$BOOTLOADER_FOUND" = "false" ]; then
    echo -e "${YELLOW}ℹ️ Không phát hiện GRUB hoặc systemd-boot. Hãy đảm bảo thêm 'nvidia_drm.modeset=1' vào bootloader của bạn.${NC}"
fi

# 4. Ghi trạng thái các thay đổi vào nvidia-state.env (chỉ khi không --dry-run)
if [ "$DRY_RUN" = "false" ]; then
    # Gộp các module đã thêm từ lần trước + lần này (không trùng lặp, giữ thứ tự)
    MERGED_MODULES=()
    for m in $PREV_ADDED_MKINITCPIO_MODULES $ADDED_MODULES_NOW; do
        seen=false
        for em in "${MERGED_MODULES[@]:-}"; do
            if [ "$em" = "$m" ]; then
                seen=true
                break
            fi
        done
        [ "$seen" = "false" ] && MERGED_MODULES+=("$m")
    done

    FINAL_GRUB_MODESET_ADDED="false"
    if [ "$PREV_GRUB_MODESET_ADDED" = "true" ] || [ "$GRUB_MODESET_ADDED_NOW" = "true" ]; then
        FINAL_GRUB_MODESET_ADDED="true"
    fi

    MERGED_ENTRIES=()
    for ep in $PREV_LOADER_ENTRIES_MODIFIED "${LOADER_ENTRIES_NOW[@]:-}"; do
        [ -z "$ep" ] && continue
        seen=false
        for ee in "${MERGED_ENTRIES[@]:-}"; do
            if [ "$ee" = "$ep" ]; then
                seen=true
                break
            fi
        done
        [ "$seen" = "false" ] && MERGED_ENTRIES+=("$ep")
    done

    FINAL_MODPROBE_CREATED="false"
    if [ "$PREV_MODPROBE_CREATED" = "true" ] || [ "$MODPROBE_CREATED_NOW" = "true" ]; then
        FINAL_MODPROBE_CREATED="true"
    fi

    ADDED_MODULES_STR=""
    if [ ${#MERGED_MODULES[@]} -gt 0 ]; then
        ADDED_MODULES_STR="${MERGED_MODULES[*]}"
    fi
    MODIFIED_ENTRIES_STR=""
    if [ ${#MERGED_ENTRIES[@]} -gt 0 ]; then
        MODIFIED_ENTRIES_STR="${MERGED_ENTRIES[*]}"
    fi

    mkdir -p "$STATE_DIR"
    tmp_state="$(mktemp "$STATE_DIR/nvidia-state.env.XXXXXX")"
    cat << EOF > "$tmp_state"
# Generated by yusei-hypr setup-nvidia.sh
ADDED_MKINITCPIO_MODULES="${ADDED_MODULES_STR}"
GRUB_MODESET_ADDED=${FINAL_GRUB_MODESET_ADDED}
LOADER_ENTRIES_MODIFIED="${MODIFIED_ENTRIES_STR}"
MODPROBE_CREATED=${FINAL_MODPROBE_CREATED}
EOF
    mv "$tmp_state" "$NVIDIA_STATE_FILE"
    echo -e "${GREEN}✓ Đã lưu trạng thái cấu hình NVIDIA vào: ${NVIDIA_STATE_FILE}${NC}"
else
    echo -e "${YELLOW}[DRY-RUN] Không ghi ${NVIDIA_STATE_FILE}.${NC}"
fi

echo -e "${GREEN}✓ Hoàn tất cấu hình tầng Kernel cho NVIDIA!${NC}\n"
