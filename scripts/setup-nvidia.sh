#!/usr/bin/env bash
# ==============================================================================
# yusei-hypr: NVIDIA Kernel & Bootloader Provisioning Module
# ==============================================================================

set -euo pipefail

GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m'

echo -e "${BLUE}:: [NVIDIA Setup] Thiết lập cấu hình chuyên sâu cho card NVIDIA...${NC}"

# Nạp thông tin phần cứng
HAS_NVIDIA="false"
if [ -f /tmp/yusei-hypr/detected.env ]; then
    # shellcheck disable=SC1091
    . /tmp/yusei-hypr/detected.env
fi

if [ "$HAS_NVIDIA" != "true" ]; then
    echo -e "${GREEN}✓ Hệ thống không dùng GPU NVIDIA (Intel / AMD Radeon). Bỏ qua bước này.${NC}"
    exit 0
fi

echo -e "${YELLOW}:: Đang tiến hành cấu hình Kernel, Initramfs và Bootloader cho NVIDIA...${NC}"

# 1. Cấu hình Modprobe (/etc/modprobe.d/nvidia.conf)
echo -e "${BLUE}:: [1/3] Cấu hình tham số kernel module (/etc/modprobe.d/nvidia.conf)...${NC}"
sudo mkdir -p /etc/modprobe.d
cat << 'EOF' | sudo tee /etc/modprobe.d/nvidia.conf > /dev/null
# Generated by yusei-hypr installer (JaKooLit parity)
options nvidia_drm modeset=1 fbdev=1
EOF
echo -e "${GREEN}✓ Đã tạo /etc/modprobe.d/nvidia.conf với options: modeset=1 fbdev=1${NC}"

# 2. Cấu hình Initramfs (/etc/mkinitcpio.conf)
echo -e "${BLUE}:: [2/3] Kiểm tra nạp module sớm (Early KMS) trong /etc/mkinitcpio.conf...${NC}"
if [ -f /etc/mkinitcpio.conf ]; then
    NVIDIA_MODULES=("nvidia" "nvidia_modeset" "nvidia_uvm" "nvidia_drm")
    MISSING_MODULES=()

    for mod in "${NVIDIA_MODULES[@]}"; do
        if ! grep -E "^\s*MODULES=\([^)]*\b${mod}\b" /etc/mkinitcpio.conf &>/dev/null; then
            MISSING_MODULES+=("$mod")
        fi
    done

    if [ ${#MISSING_MODULES[@]} -gt 0 ]; then
        echo -e "${YELLOW}Module còn thiếu trong MODULES=(...): ${MISSING_MODULES[*]}${NC}"
        echo -e "${BLUE}:: Sao lưu /etc/mkinitcpio.conf trước khi cập nhật...${NC}"
        sudo cp -a /etc/mkinitcpio.conf "/etc/mkinitcpio.conf.bak_$(date +%Y%m%d_%H%M%S)"

        # Chèn module vào MODULES=(...)
        sudo sed -i -E "s/^\s*MODULES=\((.*)\)/MODULES=(\1 ${MISSING_MODULES[*]})/" /etc/mkinitcpio.conf
        # Chuẩn hóa khoảng trắng bên trong ngoặc
        sudo sed -i -E "s/MODULES=\(\s+/MODULES=(/g; s/\s+\)/)/g" /etc/mkinitcpio.conf

        echo -e "${GREEN}✓ Đã cập nhật MODULES trong /etc/mkinitcpio.conf${NC}"
        echo -e "${BLUE}:: Đang biên dịch lại initramfs qua 'mkinitcpio -P'...${NC}"
        sudo mkinitcpio -P
        echo -e "${GREEN}✓ Đã tạo lại initramfs thành công!${NC}"
    else
        echo -e "${GREEN}✓ Toàn bộ module NVIDIA đã có mặt trong /etc/mkinitcpio.conf.${NC}"
    fi
else
    echo -e "${YELLOW}⚠️ Không tìm thấy /etc/mkinitcpio.conf (có thể hệ thống dùng booster hoặc dracut).${NC}"
fi

# 3. Cấu hình Bootloader Kernel Parameter (GRUB / systemd-boot)
echo -e "${BLUE}:: [3/3] Kiểm tra tham số dòng lệnh Bootloader...${NC}"
if [ -f /etc/default/grub ]; then
    if ! grep -q "nvidia_drm.modeset=1" /etc/default/grub && ! grep -q "nvidia-drm.modeset=1" /etc/default/grub; then
        echo -e "${YELLOW}Thêm 'nvidia_drm.modeset=1' vào GRUB_CMDLINE_LINUX_DEFAULT trong /etc/default/grub...${NC}"
        sudo cp -a /etc/default/grub "/etc/default/grub.bak_$(date +%Y%m%d_%H%M%S)"
        sudo sed -i -E 's/GRUB_CMDLINE_LINUX_DEFAULT="([^"]*)"/GRUB_CMDLINE_LINUX_DEFAULT="\1 nvidia_drm.modeset=1"/' /etc/default/grub
        sudo sed -i 's/" /"/g' /etc/default/grub

        if command -v grub-mkconfig &>/dev/null; then
            echo -e "${BLUE}:: Cập nhật cấu hình GRUB (grub-mkconfig)...${NC}"
            sudo grub-mkconfig -o /boot/grub/grub.cfg
            echo -e "${GREEN}✓ Đã cập nhật GRUB thành công!${NC}"
        else
            echo -e "${YELLOW}⚠️ Đã cập nhật /etc/default/grub nhưng không tìm thấy lệnh grub-mkconfig.${NC}"
        fi
    else
        echo -e "${GREEN}✓ GRUB đã có sẵn tham số modeset cho NVIDIA.${NC}"
    fi
elif [ -d /boot/loader/entries ]; then
    echo -e "${BLUE}:: Phát hiện systemd-boot. Kiểm tra các file entry...${NC}"
    ENTRIES_UPDATED=0
    for entry in /boot/loader/entries/*.conf; do
        if [ -f "$entry" ]; then
            if ! grep -q "nvidia_drm.modeset=1" "$entry" && ! grep -q "nvidia-drm.modeset=1" "$entry"; then
                echo -e "${YELLOW}Bổ sung 'nvidia_drm.modeset=1' vào options của $(basename "$entry")...${NC}"
                sudo cp -a "$entry" "${entry}.bak_$(date +%Y%m%d_%H%M%S)"
                sudo sed -i -E 's/^(options\s+.*)$/\1 nvidia_drm.modeset=1/' "$entry"
                ENTRIES_UPDATED=$((ENTRIES_UPDATED + 1))
            fi
        fi
    done
    if [ "$ENTRIES_UPDATED" -gt 0 ]; then
        echo -e "${GREEN}✓ Đã cập nhật $ENTRIES_UPDATED mục khởi động trong systemd-boot!${NC}"
    else
        echo -e "${GREEN}✓ systemd-boot entries đã chứa tham số modeset cho NVIDIA.${NC}"
    fi
else
    echo -e "${YELLOW}ℹ️ Không phát hiện GRUB hoặc systemd-boot. Hãy đảm bảo thêm 'nvidia_drm.modeset=1' vào bootloader của bạn.${NC}"
fi

echo -e "${GREEN}✓ Hoàn tất cấu hình tầng Kernel cho NVIDIA!${NC}\n"
